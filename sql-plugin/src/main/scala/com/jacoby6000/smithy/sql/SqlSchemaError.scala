    shape: ShapeId,
    memberName: String,
    tableRefs: List[String]
) extends SqlSchemaError {
  override def message: String =
    s"sqlDeriveSelect on ${shape.toString} member '$memberName' matches table members on ${tableRefs.mkString(", ")}; add tableRef/column in @sqlDeriveSelect or @sqlColumn(name: \"...\") to disambiguate"
